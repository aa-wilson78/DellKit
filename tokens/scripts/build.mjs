// DellKit token build
// One source (tokens/*.json, W3C DTCG format) -> three outputs:
//   build/ios/DellKitTokens.swift   SwiftUI: semantic + component tokens, light/dark resolved at runtime
//   build/web/tokens.css            CSS custom properties for the web twin (Code Layers / "send to Figma")
//   build/figma/variables.json      Figma variable collections with aliases + Light/Dark modes
//
// Run: npm run build

import StyleDictionary from 'style-dictionary';
import { mkdir, writeFile } from 'node:fs/promises';

const BASE = ['tokens/primitive/**/*.json', 'tokens/semantic/**/*.json', 'tokens/component/**/*.json'];
const MODES = {
  light: BASE,
  dark: [...BASE, 'tokens/themes/dark.json'], // later sources override earlier ones
};

// ---------- load + resolve each mode ----------
async function load(source) {
  const sd = new StyleDictionary({
    source,
    log: { warnings: 'disabled', verbosity: 'silent' }, // dark overrides are intentional collisions
    platforms: { raw: { transforms: ['name/camel'] } },
  });
  const { allTokens } = await sd.getPlatformTokens('raw');
  return allTokens;
}

const resolved = {};
for (const [mode, src] of Object.entries(MODES)) resolved[mode] = await load(src);

const byPath = (tokens) => new Map(tokens.map((t) => [t.path.join('.'), t]));
const light = byPath(resolved.light);
const dark = byPath(resolved.dark);

const tier = (t) =>
  t.filePath.includes('/primitive/') ? 'primitive'
  : t.filePath.includes('/component/') ? 'component'
  : 'semantic'; // semantic + themes/dark both count as semantic

const typeOf = (t) => t.$type ?? t.type;
const valueOf = (t) => t.$value ?? t.value;
const originalOf = (t) => t.original.$value ?? t.original.value;
const aliasOf = (t) => {
  const o = originalOf(t);
  return typeof o === 'string' && /^\{.+\}$/.test(o) ? o.slice(1, -1) : null;
};
const px = (v) => parseFloat(String(v));
const camel = (parts) =>
  parts.map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join('').replace(/[^A-Za-z0-9]/g, '');
const swiftName = (t) => camel(['color', 'component'].includes(t.path[0]) ? t.path.slice(1) : t.path);
const hex = (v) => String(v).replace('#', '').toUpperCase();

await mkdir('build/ios', { recursive: true });
await mkdir('build/web', { recursive: true });
await mkdir('build/figma', { recursive: true });

// ---------- SwiftUI ----------
// Components never see primitives: only semantic + component tokens are emitted.
{
  // Primitive COLORS stay hidden; primitive dimensions (space, radius, size) are the spacing API.
  const exposed = resolved.light.filter((t) => tier(t) !== 'primitive' || typeOf(t) === 'dimension');
  const colors = exposed.filter((t) => typeOf(t) === 'color');
  const dims = exposed.filter((t) => typeOf(t) === 'dimension');
  const type = resolved.light.filter((t) => typeOf(t) === 'typography');

  const weightName = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' };

  const colorLines = colors.map((t) => {
    const key = t.path.join('.');
    const d = dark.get(key);
    const name = swiftName(t);
    return `        /// ${key}${t.$description ? ' — ' + t.$description : ''}\n        public static let ${name} = SwiftUI.Color(light: 0x${hex(valueOf(t))}, dark: 0x${hex(valueOf(d))})`;
  });
  const dimLines = dims.map((t) => {
    const name = swiftName(t);
    return `        public static let ${name}: CGFloat = ${px(valueOf(t))}`;
  });
  const typeLines = type.map((t) => {
    const v = valueOf(t);
    const style = t.$extensions?.['ios.textStyle'] ?? 'body';
    const w = weightName[Number(v.fontWeight)] ?? 'regular';
    return `        /// ${px(v.fontSize)}pt / ${px(v.lineHeight)}pt at default Dynamic Type size\n        public static let ${t.path[1]} = SwiftUI.Font.system(.${style}, design: .default, weight: .${w})`;
  });

  const swift = `// GENERATED by scripts/build.mjs — do not edit by hand.
// Source of truth: tokens/*.json (W3C DTCG). Edit tokens, then run \`npm run build\`.

import SwiftUI
import UIKit

public enum DK {
    /// Semantic + component colors. Each resolves light/dark at render time.
    public enum Color {
${colorLines.join('\n')}
    }

    /// Spacing, radius and component dimensions (points).
    public enum Metric {
${dimLines.join('\n')}
    }

    /// Mapped to Apple text styles so Dynamic Type scales automatically.
    public enum Typography {
${typeLines.join('\n')}
    }
}

extension SwiftUI.Color {
    init(light: UInt32, dark: UInt32) {
        self.init(uiColor: UIColor { traits in
            let rgb = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(
                red:   CGFloat((rgb >> 16) & 0xFF) / 255,
                green: CGFloat((rgb >> 8) & 0xFF) / 255,
                blue:  CGFloat(rgb & 0xFF) / 255,
                alpha: 1
            )
        })
    }
}
`;
  await writeFile('build/ios/DellKitTokens.swift', swift);
  // Also drop it straight into the Swift package so the package never drifts from tokens.
  await mkdir('../ios/Sources/DellKit/Tokens', { recursive: true });
  await writeFile('../ios/Sources/DellKit/Tokens/DellKitTokens.swift', swift);
}

// ---------- CSS (web twin) ----------
{
  const cssName = (t) => '--dk-' + t.path.join('-');
  const decl = (tokens) =>
    tokens
      .filter((t) => typeOf(t) !== 'typography')
      .map((t) => `  ${cssName(t)}: ${valueOf(t)};`)
      .join('\n');
  // Figma text styles use Inter as a stand-in for SF Pro (not renderable in Figma cloud); iOS uses .system()
  const typo = resolved.light
    .filter((t) => typeOf(t) === 'typography')
    .map((t) => {
      const v = valueOf(t);
      return `  --dk-font-${t.path[1]}: ${v.fontWeight} ${v.fontSize}/${v.lineHeight} -apple-system, BlinkMacSystemFont, "SF Pro Text", system-ui, sans-serif;`;
    })
    .join('\n');
  const darkOnly = resolved.dark.filter((t) => typeOf(t) === 'color' && tier(t) !== 'primitive');

  const css = `/* GENERATED by scripts/build.mjs — do not edit by hand. */
:root {
${decl(resolved.light)}
${typo}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decl(darkOnly).replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
${decl(darkOnly)}
}
`;
  await writeFile('build/web/tokens.css', css);
}

// ---------- Figma variables ----------
// Shape is tool-agnostic: collections -> modes -> variables, aliases kept as references.
{
  const figmaName = (t) => {
    const p = t.path[0] === 'color' || t.path[0] === 'component' ? t.path.slice(1) : t.path;
    return p.join('/');
  };
  const figmaType = (t) => (typeOf(t) === 'color' ? 'COLOR' : 'FLOAT');
  const scopes = (t) => {
    if (typeOf(t) === 'color') {
      const p = t.path.join('.');
      if (/^color\.icon\./.test(p)) return ['STROKE_COLOR', 'SHAPE_FILL'];
      if (/^color\.status\.(success|warning|error|info)$|^color\.order\.|tabBar\.(active|inactive)$/.test(p))
        return ['FRAME_FILL', 'SHAPE_FILL', 'TEXT_FILL', 'STROKE_COLOR'];
      if (/text|foreground|placeholder|field\.value$/i.test(p)) return ['TEXT_FILL'];
      if (/border|divider/i.test(p)) return ['STROKE_COLOR'];
      return ['FRAME_FILL', 'SHAPE_FILL'];
    }
    if (t.path[0] === 'radius' || /radius$/i.test(t.path.at(-1))) return ['CORNER_RADIUS'];
    if (t.path.join('.').match(/height|touchTarget/i)) return ['WIDTH_HEIGHT'];
    return ['GAP'];
  };
  const collectionOf = (t) =>
    tier(t) === 'primitive' ? 'Primitives' : tier(t) === 'component' ? 'Components' : 'Semantic';

  const pathToFigma = new Map(
    resolved.light.filter((t) => typeOf(t) !== 'typography' && typeOf(t) !== 'fontFamily' && typeOf(t) !== 'fontWeight')
      .map((t) => [t.path.join('.'), { collection: collectionOf(t), name: figmaName(t) }])
  );

  const modeValue = (t) => {
    const a = aliasOf(t);
    if (a && pathToFigma.has(a)) return { alias: pathToFigma.get(a) };
    return typeOf(t) === 'color' ? valueOf(t) : px(valueOf(t));
  };

  const collections = {
    Primitives: { modes: ['Value'], variables: [] },
    Semantic: { modes: ['Light', 'Dark'], variables: [] },
    Components: { modes: ['Value'], variables: [] },
  };

  for (const t of resolved.light) {
    const key = t.path.join('.');
    if (!pathToFigma.has(key)) continue;
    const c = collectionOf(t);
    const values =
      c === 'Semantic'
        ? { Light: modeValue(t), Dark: modeValue(dark.get(key)) }
        : { Value: modeValue(t) };
    collections[c].variables.push({
      name: figmaName(t),
      type: figmaType(t),
      scopes: scopes(t),
      description: t.$description ?? '',
      codeSyntax: { iOS: `DK.${typeOf(t) === 'color' ? 'Color' : 'Metric'}.${swiftName(t)}`, WEB: `var(--dk-${t.path.join('-')})` },
      values,
    });
  }

  const textStyles = resolved.light
    .filter((t) => typeOf(t) === 'typography')
    .map((t) => {
      const v = valueOf(t);
      return { name: t.path[1], fontFamily: 'Inter' /* Figma stand-in for SF Pro */, fontWeight: Number(v.fontWeight), fontSize: px(v.fontSize), lineHeight: px(v.lineHeight) };
    });

  await writeFile('build/figma/variables.json', JSON.stringify({ collections, textStyles }, null, 2));
}

// ---------- summary ----------
const count = (m, f) => resolved[m].filter(f).length;
console.log('DellKit tokens built');
console.log(`  primitives: ${count('light', (t) => tier(t) === 'primitive')}`);
console.log(`  semantic:   ${count('light', (t) => tier(t) === 'semantic')}  (light + dark)`);
console.log(`  component:  ${count('light', (t) => tier(t) === 'component')}`);
console.log('  -> build/ios/DellKitTokens.swift');
console.log('  -> build/web/tokens.css');
console.log('  -> build/figma/variables.json');
